HOLDOUT_FRACTION_DENOMINATOR = 3


def holdout_ids(queries: Iterable[Query] = QUERIES) -> frozenset[str]:
    """A deterministic third of each category: rank the category's ids by a hash of the id,
    and hold out every third one starting with the first. Category-stratified, so every
    category is represented in both splits; never tuned on."""
    by_category: dict[str, list[str]] = defaultdict(list)
    for query in queries:
        by_category[query.category].append(query.id)
    held: set[str] = set()
    for ids in by_category.values():
        ranked = sorted(ids, key=lambda qid: (stable_hash(f"ctxbench-holdout:{qid}"), qid))
        held.update(ranked[::HOLDOUT_FRACTION_DENOMINATOR])
    return frozenset(held)


def split_of(query_id: str) -> str:
    return "holdout" if query_id in HOLDOUT else "dev"


