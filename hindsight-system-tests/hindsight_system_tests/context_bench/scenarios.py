MEMORY_BY_LABEL = {memory.label: memory for memory in MEMORIES}
LABEL_BY_DOCUMENT = {memory.document_id: memory.label for memory in MEMORIES}


def validate() -> list[str]:
    """Integrity problems in the scenario; empty when it is consistent."""
    problems: list[str] = []
    labels = [memory.label for memory in MEMORIES]
    if len(labels) != len(set(labels)):
        problems.append("duplicate memory labels")
    if len({memory.document_id for memory in MEMORIES}) != len(MEMORIES):
        problems.append("document id collision")
    if len({query.id for query in QUERIES}) != len(QUERIES):
        problems.append("duplicate query ids")
    for query in QUERIES:
        named = (*query.relevant, *query.acceptable, *query.hard_negatives)
        for label in named:
            memory = MEMORY_BY_LABEL.get(label)
            if memory is None:
                problems.append(f"{query.id}: unknown label {label}")
            elif memory.bank != query.bank:
                problems.append(f"{query.id}: {label} is in bank {memory.bank}, query in {query.bank}")
        if len(set(named)) != len(named):
            problems.append(f"{query.id}: a label is in more than one of relevant/acceptable/hard")
        if not query.relevant and query.acceptable:
            problems.append(f"{query.id}: an abstention query cannot have acceptable memories")
        if query.category not in QUERY_CATEGORIES:
            problems.append(f"{query.id}: unknown category {query.category}")
    return problems
