from .model import MAIN_BANK, QUERY_CATEGORIES, SESSION_BANK, Category, Memory, Query, stable_hash


def _project_of(label: str) -> str | None:
    head = label.split(".", 1)[0]
    if head in ("a", "b", "c"):
        return head
    if head == "bg":
        return label.rsplit(".", 1)[1]
    if head == "s":
        return "a"
    return None


def m(
    label: str,
    category: Category,
    text: str,
    *,
    module: str | None = None,
    age: int | None = None,
    status: str = "active",
    env: str | None = None,
    branch: str = "main",
) -> Memory:
    return Memory(
        label=label,
        category=category,
        text=text,
        project=_project_of(label),
        module=module,
        age_days=age if age is not None else 15 + stable_hash(label) % 300,
        status=status,  # type: ignore[arg-type]
        environment=env,
        branch=branch,
        bank=SESSION_BANK if label.startswith("s.") else MAIN_BANK,
    )


